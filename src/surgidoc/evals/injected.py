"""Injected-error eval: how many known-false claims does the verifier catch?

In the agent runs Claude wrote almost no false claims, so comparing drafts with and
without the verifier measures nothing (RESULTS.md). This eval plants errors instead.
For each checkpointed run it builds claims from that run's own facts, timeline and
retrieved passages, each with a known answer:

- error:      false given the vision output or the passages; the verifier should reject it
- blind_spot: an error the verifier cannot see by design (the vision model is wrong, or
              the claim misstates a correctly quoted passage); it should pass, and the
              rate shows how much is left to the reviewer
- control:    a true claim; it should pass (a rejection is a false alarm)

Claims are generated by code from templates, not written by an LLM, so the errors are
cleaner than real model mistakes. The catch rate is an upper bound on what the
verifier achieves on real drafts.

    python -m surgidoc.evals.injected --threads eval-video17 eval-video37 eval-video55
"""

from __future__ import annotations

import argparse
import json
import random
from collections import defaultdict
from itertools import pairwise
from pathlib import Path

from surgidoc.agent.claims import Claim
from surgidoc.agent.facts import FrameFacts, Timeline
from surgidoc.agent.perception import contiguous_runs
from surgidoc.agent.verify import STRUCTURE_WORDS, verify
from surgidoc.retrieval.chunking import load_corpus
from surgidoc.vision.phase import PHASES

from .grounding import ground_truth_facts, load_run

DEFAULT_OUT = Path("reports/eval_injected.json")
PER_CATEGORY = 5  # cases per category and run, fewer if the run offers fewer
WINDOW = 5  # frames per claim
QUOTE_WORDS = 12
STRUCTURES = list(STRUCTURE_WORDS)  # every class except background
# Expected verifier verdict per kind.
KINDS = {"error": "rejected", "blind_spot": "passed", "control": "passed"}


def name(s: str) -> str:
    return STRUCTURE_WORDS[s][0]  # a phrase the verifier recognises as this structure


def windows(facts: list[FrameFacts]) -> list[list[FrameFacts]]:
    """Consecutive WINDOW-frame stretches that do not cross a footage gap."""
    times = [f.time_s for f in facts]
    step = min(b - a for a, b in pairwise(times))
    out = []
    for run in contiguous_runs(times, max_gap_s=3 * step):
        chunk = facts[run.start : run.stop]
        out += [chunk[i : i + WINDOW] for i in range(0, len(chunk) - WINDOW + 1, WINDOW)]
    return out


def ids(frames: list[FrameFacts]) -> list[int]:
    return [f.frame_id for f in frames]


def span(text: str, rng: random.Random) -> str:
    words = text.split()
    start = rng.randrange(0, max(1, len(words) - QUOTE_WORDS))
    return " ".join(words[start : start + QUOTE_WORDS])


class Generator:
    def __init__(self, facts, gt_facts, timeline: Timeline, passages: dict[str, str],
                 corpus: dict[str, str], rng: random.Random) -> None:
        self.facts, self.gt, self.timeline = facts, gt_facts, timeline
        self.passages, self.corpus, self.rng = passages, corpus, rng
        self.windows = windows(facts)
        self.n = 0

    def claim(self, **fields) -> Claim:
        self.n += 1
        return Claim(id=f"x{self.n}", **fields)

    def sample(self, items: list) -> list:
        return self.rng.sample(items, min(PER_CATEGORY, len(items)))

    # --- errors --------------------------------------------------------------------

    def absent_structure(self):
        cases = [(w, s) for w in self.windows for s in STRUCTURES
                 if not any(f.visible(s) for f in w)]
        for w, s in self.sample(cases):
            yield self.claim(claim_type="structures_visible", text=f"The {name(s)} is visible.",
                             frame_ids=ids(w), structures=[s])

    def partial_support(self):
        """Half the cited frames show the structure: below the 80% the verifier requires."""
        cases = []
        for s in STRUCTURES:
            seen = [f for f in self.facts if f.visible(s)]
            unseen = [f for f in self.facts if not f.visible(s)]
            if len(seen) >= 3 and len(unseen) >= 3:
                cases.append(s)
        for s in self.sample(cases):
            seen = self.rng.sample([f for f in self.facts if f.visible(s)], 3)
            unseen = self.rng.sample([f for f in self.facts if not f.visible(s)], 3)
            yield self.claim(claim_type="structures_visible", text=f"The {name(s)} is visible.",
                             frame_ids=sorted(ids(seen + unseen)), structures=[s])

    def wrong_phase(self):
        cases = [w for w in self.windows if len({f.phase for f in w}) == 1]
        for w in self.sample(cases):
            wrong = self.rng.choice([p for p in PHASES if p != w[0].phase])
            yield self.claim(claim_type="phase", text=f"This is the {wrong.replace('_', ' ')} "
                             "phase.", frame_ids=ids(w), phase=wrong)

    def unknown_frames(self):
        n = len(self.facts)
        for k in range(PER_CATEGORY):
            yield self.claim(claim_type="structures_visible", text="The liver is visible.",
                             frame_ids=list(range(n + 10 * k, n + 10 * k + WINDOW)),
                             structures=["liver"])

    def unknown_event(self):
        n = len(self.timeline.events)
        for k in range(PER_CATEGORY):
            yield self.claim(claim_type="event", text="The grasper is in view.",
                             event_ids=[f"E{n + k + 1}"], structures=["grasper"])

    def unlisted_structure(self):
        """True about one structure, but the text also names one that is absent."""
        cases = [(w, s, t) for w in self.windows for s in STRUCTURES for t in STRUCTURES
                 if all(f.visible(s) for f in w) and not any(f.visible(t) for f in w)]
        for w, s, t in self.sample(cases):
            yield self.claim(claim_type="structures_visible",
                             text=f"The {name(s)} is visible next to the {name(t)}.",
                             frame_ids=ids(w), structures=[s])

    def unretrieved_passage(self):
        others = [p for p in self.corpus if p not in self.passages]
        for pid in self.sample(others):
            yield self.claim(claim_type="guideline", text="Guidance on this step.",
                             passage_ids=[pid], quote=span(self.corpus[pid], self.rng))

    def altered_quote(self):
        """A real span with one word swapped for another word from the same passage."""
        for pid in self.sample(list(self.passages)):
            words = span(self.passages[pid], self.rng).split()
            i = self.rng.randrange(len(words))
            words[i] = self.rng.choice([w for w in self.passages[pid].split()
                                        if w.lower() != words[i].lower()])
            yield self.claim(claim_type="guideline", text="Guidance on this step.",
                             passage_ids=[pid], quote=" ".join(words))

    def quote_from_other_passage(self):
        pids = list(self.passages)
        for pid in self.sample(pids):
            other = self.rng.choice([p for p in pids if p != pid])
            yield self.claim(claim_type="guideline", text="Guidance on this step.",
                             passage_ids=[pid], quote=span(self.passages[other], self.rng))

    def guideline_with_observation(self):
        for pid, w in zip(self.sample(list(self.passages)), self.sample(self.windows)):
            yield self.claim(claim_type="guideline", text="This step followed the guidance.",
                             passage_ids=[pid], quote=span(self.passages[pid], self.rng),
                             frame_ids=ids(w))

    # --- blind spots -------------------------------------------------------------

    def vision_error(self):
        """The model sees the structure in every cited frame (1-3 frames); the masks do not."""
        gt = {f.frame_id: f for f in self.gt}
        cases = [(s, f) for s in STRUCTURES for f in self.facts
                 if f.visible(s) and not gt[f.frame_id].visible(s)]
        for s, f in self.sample(cases):
            near = [g for g in self.facts if abs(g.frame_id - f.frame_id) <= 1
                    and g.visible(s) and not gt[g.frame_id].visible(s)]
            yield self.claim(claim_type="structures_visible", text=f"The {name(s)} is visible.",
                             frame_ids=ids(near), structures=[s])

    def misstated_guideline(self):
        """A verbatim quote, with a claim that turns it around."""
        for pid in self.sample(list(self.passages)):
            yield self.claim(claim_type="guideline",
                             text="Guidance states that this is optional and can be skipped.",
                             passage_ids=[pid], quote=span(self.passages[pid], self.rng))

    # --- controls ------------------------------------------------------------------

    def true_structure(self):
        cases = [(w, s) for w in self.windows for s in STRUCTURES
                 if all(f.visible(s) for f in w)]
        for w, s in self.sample(cases):
            yield self.claim(claim_type="structures_visible", text=f"The {name(s)} is visible.",
                             frame_ids=ids(w), structures=[s])

    def true_phase(self):
        cases = [w for w in self.windows if len({f.phase for f in w}) == 1]
        for w in self.sample(cases):
            yield self.claim(claim_type="phase", text="Phase estimate for these frames.",
                             frame_ids=ids(w), phase=w[0].phase)

    def true_guideline(self):
        for pid in self.sample(list(self.passages)):
            yield self.claim(claim_type="guideline", text="Guidance on this step.",
                             passage_ids=[pid], quote=span(self.passages[pid], self.rng))


CATEGORIES = {
    "absent_structure": "error", "partial_support": "error", "wrong_phase": "error",
    "unknown_frames": "error", "unknown_event": "error", "unlisted_structure": "error",
    "unretrieved_passage": "error", "altered_quote": "error",
    "quote_from_other_passage": "error", "guideline_with_observation": "error",
    "vision_error": "blind_spot", "misstated_guideline": "blind_spot",
    "true_structure": "control", "true_phase": "control", "true_guideline": "control",
}


def run_eval(facts, gt_facts, timeline, passages, corpus, seed: int) -> list[dict]:
    gen = Generator(facts, gt_facts, timeline, passages, corpus, random.Random(seed))
    rows = []
    for category, kind in CATEGORIES.items():
        claims = list(getattr(gen, category)())
        results = verify(claims, facts, timeline, passages).results
        for c, r in zip(claims, results):
            verdict = "passed" if r.status == "supported" else "rejected"
            rows.append({"category": category, "kind": kind, "claim": c.model_dump(),
                         "status": r.status, "reasons": r.reasons,
                         "correct": verdict == KINDS[kind]})
    return rows


def summarise(rows: list[dict]) -> dict:
    by = defaultdict(list)
    for r in rows:
        by[r["category"]].append(r)
    out = {}
    for category, items in by.items():
        rejected = sum(r["status"] != "supported" for r in items)
        out[category] = {"kind": items[0]["kind"], "n": len(items), "rejected": rejected,
                         "rejected_rate": rejected / len(items)}
    for kind in KINDS:
        items = [r for r in rows if r["kind"] == kind]
        rejected = sum(r["status"] != "supported" for r in items)
        out[f"all_{kind}"] = {"kind": kind, "n": len(items), "rejected": rejected,
                              "rejected_rate": rejected / len(items) if items else None}
    return out


def main() -> None:
    from langgraph.checkpoint.sqlite import SqliteSaver

    from surgidoc.agent.graph import CHECKPOINT_DB

    p = argparse.ArgumentParser()
    p.add_argument("--threads", nargs="+", required=True)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = p.parse_args()

    corpus = {c.id: c.text for c in load_corpus()}
    rows = []
    with SqliteSaver.from_conn_string(str(CHECKPOINT_DB)) as saver:
        for i, thread in enumerate(args.threads):
            run = load_run(saver, thread)
            gt = ground_truth_facts(run["facts"])
            for r in run_eval(run["facts"], gt, run["timeline"], run["passages"], corpus,
                              seed=args.seed + i):
                rows.append({"thread": thread, **r})

    summary = summarise(rows)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps({"seed": args.seed, "threads": args.threads,
                                    "summary": summary, "rows": rows}, indent=1))

    print("| Category | Kind | Expected | n | Rejected | Rejected rate |")
    print("|---|---|---|---:|---:|---:|")
    for category, s in summary.items():
        print(f"| {category} | {s['kind']} | {KINDS[s['kind']]} | {s['n']} | {s['rejected']} | "
              f"{s['rejected_rate']:.2f} |")
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
